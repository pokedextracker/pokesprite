// This script looks at the `images` directory and generates a .css file with
// the classes, spritesheets, and `background-position`s so that the
// spritesheets can be used for PokedexTracker.
//
// Every icon's rule names its own spritesheet instead of a class like
// .color-shiny picking one. An icon without a variant for a dex falls back to a
// less specific rule (e.g. a shiny dex shows the regular icon when there's no
// shiny one), and the spritesheet has to fall back with the position.
//
// The rules are written in file name order across all the spritesheets, not
// grouped by spritesheet. When two rules are equally specific, the later one
// wins, so the order decides which icon shows for a combination with no icon
// of its own (e.g. a form without a Legends: Arceus icon in that dex).
//
// The URLs are relative to where the `copy` task puts the stylesheet in
// pokedextracker.com (app/styles), so Vite bundles the spritesheets and gives
// them hashed names.
package main

import (
	"bytes"
	"fmt"
	"os"
	"sort"

	"github.com/pokedextracker/pokesprite/pkg/sheet"
)

const (
	imagesURL = "../images/"

	preamble = `/* The spritesheets of Pokémon icons: an icon is .pkicon with its number,
   form, and shininess. Generated by the css script in
   https://github.com/pokedextracker/pokesprite, so don't edit it by hand. */
.pkicon {
  -ms-interpolation-mode: nearest-neighbor;
  image-rendering: -moz-crisp-edges;
  image-rendering: -webkit-crisp-edges;
  image-rendering: pixelated;
  display: inline-block;
  background-repeat: no-repeat;
}

.pkicon.game-family-legends_arceus {
  border-radius: 50%%;
}

.pkicon.pkicon-ball-love { %s }

`
)

func main() {
	var buf bytes.Buffer

	width, height, err := sheet.Size(sheet.LoveBall)
	if err != nil {
		panic(err)
	}
	fmt.Fprintf(&buf, preamble, styles(sheet.LoveBall, width, height, 0, 0))

	sheets, err := sheet.Load()
	if err != nil {
		panic(err)
	}
	type rule struct {
		icon  sheet.Icon
		sheet string
	}
	var rules []rule
	for _, s := range sheets {
		for _, icon := range s.Icons {
			rules = append(rules, rule{icon, s.Name})
		}
	}
	sort.Slice(rules, func(i, j int) bool { return rules[i].icon.File < rules[j].icon.File })
	for _, r := range rules {
		fmt.Fprintf(&buf, "%s { %s }\n", r.icon.Selector, styles(r.sheet+".webp", r.icon.Width, r.icon.Height, r.icon.X, r.icon.Y))
	}

	err = os.WriteFile("./output/pokesprite.css", buf.Bytes(), 0644)
	if err != nil {
		panic(err)
	}
}

func styles(file string, width, height, x, y int) string {
	// Due to the way background-position works, these values need to be
	// negative.
	return fmt.Sprintf(
		`width: %dpx; height: %dpx; background-image: url("%s%s"); background-position: %dpx %dpx;`,
		width,
		height,
		imagesURL,
		file,
		x*-1,
		y*-1,
	)
}
